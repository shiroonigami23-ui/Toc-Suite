// Builds assets/vendor/lucide-icons.js: only the Lucide icons this app actually uses (~40 KB instead
// of the 487 KB full bundle), with a drop-in window.lucide.createIcons(). Needs the lucide npm package:
//   npm i --no-save lucide@1.73.0 && node tools/build-icons.mjs
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { createRequire } from 'node:module';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const require = createRequire(import.meta.url);
const lucidePath = process.env.LUCIDE_UMD || require.resolve('lucide/dist/umd/lucide.js');
const { icons } = require(lucidePath);
const pascal = (k) => k.split('-').map(p => p[0].toUpperCase() + p.slice(1)).join('');

const files = [];
const walk = (d) => { for (const f of readdirSync(d)) { const p = join(d, f); if (statSync(p).isDirectory()) { if (!/^(node_modules|\.git|tests|tools|docs|data)$/.test(f)) walk(p); } else if (/\.(js|html)$/.test(f) && !p.includes('assets/vendor')) files.push(p); } };
walk(root);
// Any kebab-case string literal or data-lucide value that names a Lucide icon is kept, so icons
// chosen at runtime (e.g. addLogMessage(msg, 'check-circle')) are included too.
const used = new Set();
for (const f of files) for (const m of readFileSync(f, 'utf8').matchAll(/(?:data-lucide=\\?["']|["'`])([a-z][a-z0-9]*(?:-[a-z0-9]+)*)(?=\\?["'`])/g)) if (icons[pascal(m[1])]) used.add(m[1]);
const subset = Object.fromEntries([...used].sort().map(k => [k, icons[pascal(k)]]));

const runtime = `/* Lucide icons (ISC License, https://lucide.dev) — subset of ${used.size} icons used by Toc-Suite.
   Generated by tools/build-icons.mjs; do not edit by hand. */
(function () {
  var ICONS = ${JSON.stringify(subset)};
  var NS = 'http://www.w3.org/2000/svg';
  var BASE = { xmlns: NS, width: 24, height: 24, viewBox: '0 0 24 24', fill: 'none', stroke: 'currentColor', 'stroke-width': 2, 'stroke-linecap': 'round', 'stroke-linejoin': 'round' };
  function build(name, el, extra) {
    var node = ICONS[name];
    if (!node) return null;
    var svg = document.createElementNS(NS, 'svg');
    var attrs = Object.assign({}, BASE, extra || {});
    Object.keys(attrs).forEach(function (k) { svg.setAttribute(k, attrs[k]); });
    Array.prototype.forEach.call(el.attributes, function (a) { if (a.name !== 'data-lucide') svg.setAttribute(a.name, a.value); });
    svg.setAttribute('class', ['lucide', 'lucide-' + name, el.getAttribute('class') || ''].join(' ').trim());
    svg.setAttribute('data-lucide', name);
    svg.setAttribute('aria-hidden', el.getAttribute('aria-label') ? 'false' : 'true');
    node.forEach(function (child) {
      var c = document.createElementNS(NS, child[0]);
      Object.keys(child[1] || {}).forEach(function (k) { c.setAttribute(k, child[1][k]); });
      svg.appendChild(c);
    });
    return svg;
  }
  function createIcons(opts) {
    opts = opts || {};
    var roots = opts.nodes ? Array.prototype.slice.call(opts.nodes) : [opts.root || document];
    roots.forEach(function (r) {
      if (!r) return;
      var list = [];
      if (r.matches && r.matches('[data-lucide]') && r.tagName.toLowerCase() !== 'svg') list.push(r);
      if (r.querySelectorAll) list = list.concat(Array.prototype.slice.call(r.querySelectorAll('[data-lucide]')));
      list.forEach(function (el) {
        if (el.tagName.toLowerCase() === 'svg' || !el.parentNode) return;
        var svg = build(el.getAttribute('data-lucide'), el, opts.attrs);
        if (svg) el.parentNode.replaceChild(svg, el);
      });
    });
  }
  window.lucide = { createIcons: createIcons, icons: ICONS };
  // Studios inject their HTML after load; convert any new <i data-lucide> automatically so an icon
  // can never stay blank because a refresh call was skipped or ran too early.
  var pending = false;
  function sweep() { pending = false; createIcons(); }
  function start() {
    createIcons();
    new MutationObserver(function (records) {
      if (pending) return;
      for (var i = 0; i < records.length; i++) {
        if (records[i].addedNodes.length || records[i].attributeName === 'data-lucide') { pending = true; requestAnimationFrame(sweep); return; }
      }
    }).observe(document.documentElement, { childList: true, subtree: true, attributes: true, attributeFilter: ['data-lucide'] });
  }
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', start); else start();
})();
`;
writeFileSync(join(root, 'assets/vendor/lucide-icons.js'), runtime);
console.log(`${used.size} icons, ${(runtime.length / 1024).toFixed(1)} KB`);
